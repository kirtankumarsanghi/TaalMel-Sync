"""Render the multi-year dossier with fpdf2.

Plain and printable, like the one-page export. Every section states its basis, and the
last section lists the records that could not be read so an absent medicine is never
mistaken for a medicine that was never prescribed.
"""

from __future__ import annotations

from fpdf import FPDF

MARGIN = 14
LINE = 4.6


class _Doc(FPDF):
    def header(self) -> None:  # noqa: D102 - fpdf hook
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(120, 120, 120)
        self.cell(0, 6, "Taalmel Sync  -  longitudinal medical record", new_x="LMARGIN",
                  new_y="NEXT")
        self.set_draw_color(220, 220, 220)
        self.line(MARGIN, self.get_y() + 1, 210 - MARGIN, self.get_y() + 1)
        self.ln(4)

    def footer(self) -> None:  # noqa: D102 - fpdf hook
        self.set_y(-14)
        self.set_font("Helvetica", "I", 7.5)
        self.set_text_color(140, 140, 140)
        self.cell(0, 5, f"Page {self.page_no()}  -  generated by Taalmel Sync",
                  align="C")


def _safe(text: str | None) -> str:
    """fpdf core fonts are Latin-1; replace anything outside it rather than crash."""
    if not text:
        return ""
    return (
        text.replace("\u2014", "-")
        .replace("\u2013", "-")
        .replace("\u2019", "'")
        .replace("\u2018", "'")
        .replace("\u2192", "->")
        .encode("latin-1", "replace")
        .decode("latin-1")
    )


def _section(pdf: FPDF, title: str) -> None:
    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(12, 17, 16)
    pdf.cell(0, 7, title, new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(200, 200, 200)
    pdf.line(MARGIN, pdf.get_y(), 210 - MARGIN, pdf.get_y())
    pdf.ln(2)


def _row(pdf: FPDF, cells: list[tuple[str, float]], *, bold: bool = False, size: float = 8.5) -> None:
    pdf.set_font("Helvetica", "B" if bold else "", size)
    for text, width in cells:
        pdf.cell(width, 5, _safe(text), border=0)
    pdf.ln(5)


def render_dossier(dossier: dict) -> bytes:
    pdf = _Doc(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(MARGIN, 12, MARGIN)
    pdf.add_page()

    counts = dossier["counts"]
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(12, 17, 16)
    pdf.cell(0, 9, _safe(dossier["patient_name"]), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 8.5)
    pdf.set_text_color(110, 110, 110)
    pdf.multi_cell(
        0,
        5,
        _safe(
            f"Records span {dossier['period']}   |   "
            f"{counts['prescriptions']} prescriptions, {counts['medicines']} medicines, "
            f"{counts['lab_tests']} lab tests, {counts['confirmed_conditions']} confirmed conditions\n"
            f"Generated {dossier['generated_at'].strftime('%d %b %Y, %H:%M UTC')}   |   "
            "Compiled from human-verified prescription lines only."
        ),
        new_x="LMARGIN",
        new_y="NEXT",
    )

    _section(pdf, "Conditions")
    if not dossier["conditions"]:
        _row(pdf, [("No confirmed diagnosis has been recorded.", 180)])
    else:
        for condition in dossier["conditions"]:
            _row(
                pdf,
                [
                    (condition["name"], 120),
                    (condition["date"] or "date not recorded", 60),
                ],
            )
    unconfirmed = sum(
        1 for condition in dossier["years"] for visit in condition["visits"]
        for c in visit["conditions"] if not c["confirmed"]
    )
    if unconfirmed:
        pdf.set_font("Helvetica", "I", 7.5)
        pdf.set_text_color(150, 90, 10)
        pdf.multi_cell(
            0, 4.2,
            _safe(f"{unconfirmed} diagnosis mention(s) were read but not confirmed, so they "
                  "are left out of the grouping above."),
            new_x="LMARGIN", new_y="NEXT",
        )

    _section(pdf, "Medicines by year")
    if not dossier["years"]:
        _row(pdf, [("No verified prescription lines yet.", 180)])
    for year in dossier["years"]:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(12, 17, 16)
        pdf.cell(0, 6, _safe(str(year["year"])), new_x="LMARGIN", new_y="NEXT")
        for visit in year["visits"]:
            heading = visit["date"] or "Date not recorded"
            if visit["prescriber"]:
                heading += f"  -  {visit['prescriber']}"
            pdf.set_font("Helvetica", "B", 8.5)
            pdf.set_text_color(80, 80, 80)
            pdf.cell(0, 4.6, _safe(heading), new_x="LMARGIN", new_y="NEXT")
            if visit["conditions"]:
                pdf.set_font("Helvetica", "I", 7.8)
                pdf.set_text_color(110, 110, 110)
                pdf.multi_cell(
                    0, 4.2,
                    _safe("Diagnosis read: " + ", ".join(c["name"] for c in visit["conditions"])),
                    new_x="LMARGIN", new_y="NEXT",
                )
            for medicine in visit["medicines"]:
                detail = medicine["name"]
                if medicine["dose"]:
                    detail += f"   {medicine['dose']}"
                if medicine["frequency"]:
                    detail += f"   {medicine['frequency']}"
                _row(pdf, [("   -  " + detail, 180)])
            if visit["filename"]:
                pdf.set_font("Helvetica", "", 7)
                pdf.set_text_color(140, 140, 140)
                pdf.cell(0, 4, _safe(f"   source: {visit['filename']}"),
                         new_x="LMARGIN", new_y="NEXT")

    _section(pdf, "Dose changes")
    changes = [
        (medicine, episode)
        for medicine in dossier["medications"]
        for episode in medicine["episodes"]
        if episode["dose_changed"]
    ]
    if not changes:
        _row(pdf, [("No dose change was recorded between verified prescriptions.", 180)])
    else:
        for medicine, episode in changes:
            _row(
                pdf,
                [
                    (medicine["generic"], 70),
                    (f"{episode['previous_dose'] or 'not recorded'} -> {episode['dose'] or 'not recorded'}", 70),
                    (episode["start"] or "date not recorded", 40),
                ],
            )

    _section(pdf, "Lab comparison")
    if not dossier["labs"]:
        _row(pdf, [("No lab values have been read yet.", 180)])
    else:
        _row(pdf, [("Test", 65), ("Latest", 45), ("Printed range", 45),
                   ("Position", 25)], bold=True, size=8)
        for test in dossier["labs"]:
            latest = test["points"][-1] if test["points"] else None
            printed = ""
            if latest and (latest["range_low"] is not None or latest["range_high"] is not None):
                printed = f"{latest['range_low'] if latest['range_low'] is not None else ''}"
                printed += " - "
                printed += f"{latest['range_high'] if latest['range_high'] is not None else ''}"
            latest_text = f"{test['latest_value'] or ''} {test['unit'] or ''}".strip()
            if test["latest_date"]:
                latest_text += f"  ({test['latest_date']})"
            _row(
                pdf,
                [
                    (test["test_name"], 65),
                    (latest_text or "not comparable", 45),
                    (printed or "not printed", 45),
                    (test["latest_status"].title(), 25),
                ],
                size=8,
            )
        pdf.set_font("Helvetica", "I", 7.2)
        pdf.set_text_color(130, 130, 130)
        pdf.multi_cell(
            0, 4,
            _safe("Position is the value's place relative to the range printed on its own "
                  "report. It is not a judgement that a value is healthy or abnormal."),
            new_x="LMARGIN", new_y="NEXT",
        )

    _section(pdf, "Sources")
    if not dossier["sources"]:
        _row(pdf, [("No documents recorded.", 180)])
    for source in dossier["sources"]:
        detail = source["date"] or "date not recorded"
        detail += f"   {source['filename']}"
        if source["prescriber"]:
            detail += f"   -  {source['prescriber']}"
        detail += "   (confirmed)" if source["verified"] else "   (not confirmed)"
        _row(pdf, [(detail, 180)], size=8)

    _section(pdf, "Records that could not be read")
    if not dossier["unreadable"]:
        _row(pdf, [("None. Every uploaded record produced usable text.", 180)])
    else:
        for item in dossier["unreadable"]:
            _row(
                pdf,
                [
                    (item["filename"], 90),
                    (item["date"] or "date not recorded", 30),
                    (item["status"], 60),
                ],
                size=8,
            )
        pdf.set_font("Helvetica", "I", 7.2)
        pdf.set_text_color(150, 90, 10)
        pdf.multi_cell(
            0, 4,
            _safe("A medicine may be missing from this record because of an unreadable page. "
                  "Re-read the page in the app, or add the medicine by hand."),
            new_x="LMARGIN", new_y="NEXT",
        )

    return bytes(pdf.output())
