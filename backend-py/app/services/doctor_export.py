"""Doctor export: a sourced, dated medication history a doctor can read in an appointment.

This is the doctor-to-doctor continuity artifact (§2.2A). It is produced by reading the
event record back, not by generating an answer. Every fact carries its source and age.

Content rules:
- It never diagnoses and never recommends treatment. A fixed note states this.
- Adherence is labelled "reported", never "actual".
- A medicine with no evidence reports UNKNOWN; nothing is inferred.
"""

import json
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime

from sqlmodel import Session, select

from app.consent.service import authorize_member
from app.db.models import (
    Case,
    DoctorQuestion,
    HouseholdMember,
    Medication,
    Prescription,
    PrescriptionItem,
)
from app.engines.cases import OPEN_STATUSES
from app.engines.state import MedicationState, compute_state
from app.events import store as events
from app.events.types import CaseStatus, EventType
from app.services.lab_reports import assemble_lab_findings
from app.services.reconciliation import CaseError

NOTE = (
    "Generated by Taalmel Sync. This is a structured summary of recorded evidence for "
    "clinical review, not a diagnosis or treatment recommendation."
)

# Events that describe a change in what the patient is doing, in the order a doctor reads them.
TIMELINE_EVENTS = {
    EventType.MEDICATION_NORMALIZED: "Prescribed",
    EventType.MEDICATION_NORMALIZATION_REVIEW: "Prescribed (pending review)",
    EventType.DOSE_CHANGED: "Dose changed",
    EventType.MEDICATION_REPORTED: "Patient reported",
    EventType.AVAILABILITY_OBSERVED: "Caregiver checked at home",
    EventType.MEDICATION_CONFIRMED: "Status confirmed",
    EventType.REASON_RECORDED: "Reason recorded",
    EventType.CASE_RESOLVED: "Case resolved",
    EventType.CONFLICT_DETECTED: "Discrepancy detected",
}

# Prescription-level events are recorded against the member, so they get their own
# readable labels when folded into a medicine's timeline.
_PRESCRIPTION_LABELS = {
    EventType.PRESCRIPTION_UPLOADED: "Prescription uploaded",
    EventType.PRESCRIPTION_OCR_COMPLETED: "Prescription read by OCR",
    EventType.PRESCRIPTION_VERIFIED: "Prescription confirmed by a person",
}


@dataclass(frozen=True)
class TimelineEntry:
    date: datetime
    label: str
    detail: str
    source: str
    age_days: int


@dataclass(frozen=True)
class MedicationSummary:
    medication_id: str
    name: str
    current_dose: str | None
    prescribed_by: str | None
    prescribed_on: datetime | None
    dimensions: dict[str, dict]
    open_cases: int
    resolved_cases: int
    still_uncertain_cases: int
    evidence_basis: str
    timeline: list[TimelineEntry]


@dataclass(frozen=True)
class DoctorExport:
    generated_at: datetime
    patient_id: str
    patient_name: str
    medications: list[MedicationSummary]
    unresolved_case_count: int
    questions_to_discuss: list[str]
    note: str
    # Lab values with reported adherence in the window before each test. Correlation
    # only: values are shown verbatim and never interpreted.
    lab_findings: list[dict] = field(default_factory=list)


def _describe(event_type: str, payload: dict) -> str:
    if event_type == EventType.DOSE_CHANGED:
        return f"Dose changed to {payload.get('new_dose')} (by {payload.get('changed_by') or 'unknown'})"
    if event_type == EventType.MEDICATION_REPORTED:
        if payload.get("taking"):
            return "Patient reported taking it"
        reason = payload.get("reason")
        return f"Patient reported stopping" + (f" ({reason.lower().replace('_', ' ')})" if reason else "")
    if event_type == EventType.AVAILABILITY_OBSERVED:
        status = "found at home" if payload.get("present") else "not found at home"
        expiry = payload.get("expiry_date")
        return f"{status}" + (f", expiry recorded as {str(expiry)[:10]}" if expiry else "")
    if event_type == EventType.MEDICATION_CONFIRMED:
        return f"Status confirmed as {payload.get('status', '').lower()}"
    if event_type == EventType.REASON_RECORDED:
        return f"Reason: {str(payload.get('reason_code', '')).lower().replace('_', ' ')}"
    if event_type == EventType.CONFLICT_DETECTED:
        return str(payload.get("description", "Discrepancy recorded"))
    return event_type


def _age_days(when: datetime, now: datetime) -> int:
    aware = when if when.tzinfo else when.replace(tzinfo=UTC)
    return (now - aware).days


def _build_timeline(session: Session, medication_id: str, now: datetime) -> list[TimelineEntry]:
    """Every dated fact about this medicine, in the order it happened.

    Prescription-level events (uploaded, OCR, verified) are recorded against the
    household member rather than the medicine, so they are pulled in here by joining
    through the prescription item. Without this the timeline would show only the
    normalisation step, which is exactly the history the export exists to provide.
    """
    entries: list[TimelineEntry] = []

    med = session.get(Medication, medication_id)
    prescription_ids: set[str] = set()
    if med is not None and med.prescription_item_id:
        item = session.get(PrescriptionItem, med.prescription_item_id)
        if item is not None:
            prescription_ids.add(item.prescription_id)

    for event in events.events_for_medication(session, medication_id):
        label = TIMELINE_EVENTS.get(event.event_type)
        if label is None:
            continue
        payload = json.loads(event.payload)
        entries.append(
            TimelineEntry(
                date=event.occurred_at,
                label=label,
                detail=_describe(event.event_type, payload),
                source=event.source,
                age_days=_age_days(event.occurred_at, now),
            )
        )

    # Prescription-level events that belong to this medicine.
    if prescription_ids and med is not None:
        member_events = events.events_for_member(session, med.household_member_id)
        for event in member_events:
            if event.event_type not in {
                EventType.PRESCRIPTION_UPLOADED,
                EventType.PRESCRIPTION_OCR_COMPLETED,
                EventType.PRESCRIPTION_VERIFIED,
            }:
                continue
            payload = json.loads(event.payload)
            if str(payload.get("prescription_id")) not in prescription_ids:
                continue
            entries.append(
                TimelineEntry(
                    date=event.occurred_at,
                    label="Prescription",
                    detail=_PRESCRIPTION_LABELS.get(event.event_type, event.event_type),
                    source=event.source,
                    age_days=_age_days(event.occurred_at, now),
                )
            )

    return sorted(entries, key=lambda e: e.date)


def _prescriber(session: Session, med: Medication) -> tuple[str | None, datetime | None]:
    if not med.prescription_item_id:
        return None, None
    item = session.get(PrescriptionItem, med.prescription_item_id)
    if item is None:
        return None, None
    prescription = session.get(Prescription, item.prescription_id)
    if prescription is None:
        return None, None
    return prescription.prescribed_by, prescription.prescribed_on or prescription.created_at


def _dimension_payload(dim) -> dict:
    return {
        "status": dim.status,
        "last_verified": dim.last_verified.isoformat() if dim.last_verified else None,
        "age_days": dim.age_days,
        "stale": dim.stale,
        "source_event_id": dim.source_event_id,
    }


def _evidence_basis(state: MedicationState) -> str:
    known = [
        name
        for name, dim in (
            ("prescribed", state.prescribed),
            ("available", state.available),
            ("reported taking", state.reported_taking),
            ("confirmed status", state.confirmed_status),
        )
        if dim.status != "UNKNOWN"
    ]
    if not known:
        return "No evidence recorded yet. Nothing here is inferred."
    return "Based on recorded evidence: " + ", ".join(known) + "."


def build_export(session: Session, *, user_id: str, household_member_id: str) -> DoctorExport:
    member = authorize_member(session, user_id, household_member_id)
    return _build(session, member.id, member.display_name)


def build_export_without_access(session: Session, household_member_id: str) -> DoctorExport:
    """Typed export for callers that already established access.

    Used by the token-gated public route, where the token itself is the credential.
    Never call this from an authenticated route without an access check first.
    """
    member = session.get(HouseholdMember, household_member_id)
    if member is None:
        raise CaseError("Patient not found", status_code=404)
    return _build(session, member.id, member.display_name)


def build_export_for_public(session: Session, *, household_member_id: str) -> dict:
    """Used by the token-gated public route. The token has already established access
    to exactly this patient, so no caregiver authorization is applied here."""
    member = session.get(HouseholdMember, household_member_id)
    if member is None:
        raise CaseError("Patient not found", status_code=404)

    export = _build(session, member.id, member.display_name)
    data = asdict(export)
    data["generated_at"] = export.generated_at.isoformat()
    for med in data["medications"]:
        if med["prescribed_on"] is not None:
            med["prescribed_on"] = med["prescribed_on"].isoformat()
        for entry in med["timeline"]:
            entry["date"] = entry["date"].isoformat()
    return data


def _lab_findings(session: Session, patient_id: str) -> list[dict]:
    # Access has already been established by the caller (authorize_member or the public token).
    return assemble_lab_findings(session, patient_id)


def _build(session: Session, patient_id: str, patient_name: str) -> DoctorExport:
    now = datetime.now(UTC)
    meds = session.exec(
        select(Medication).where(Medication.household_member_id == patient_id)
    ).all()

    summaries: list[MedicationSummary] = []
    unresolved = 0
    for med in meds:
        state = compute_state(med.id, list(events.events_for_medication(session, med.id)))
        cases = session.exec(select(Case).where(Case.medication_id == med.id)).all()
        open_cases = [c for c in cases if CaseStatus(c.status) in OPEN_STATUSES]
        unresolved += len(open_cases)
        prescribed_by, prescribed_on = _prescriber(session, med)

        summaries.append(
            MedicationSummary(
                medication_id=med.id,
                name=med.name_generic or med.name_raw,
                current_dose=state.current_dose,
                prescribed_by=prescribed_by,
                prescribed_on=prescribed_on,
                dimensions={
                    "prescribed": _dimension_payload(state.prescribed),
                    "available": _dimension_payload(state.available),
                    "reported_taking": _dimension_payload(state.reported_taking),
                    "confirmed_status": _dimension_payload(state.confirmed_status),
                },
                open_cases=len(open_cases),
                resolved_cases=len([c for c in cases if c.status == CaseStatus.RESOLVED.value]),
                still_uncertain_cases=len(
                    [c for c in cases if c.status == CaseStatus.STILL_UNCERTAIN.value]
                ),
                evidence_basis=_evidence_basis(state),
                timeline=_build_timeline(session, med.id, now),
            )
        )

    questions = session.exec(
        select(DoctorQuestion)
        .where(
            DoctorQuestion.household_member_id == patient_id,
            DoctorQuestion.status == "PENDING",
        )
        .order_by(DoctorQuestion.created_at)  # type: ignore[arg-type]
    ).all()

    return DoctorExport(
        generated_at=now,
        patient_id=patient_id,
        patient_name=patient_name,
        medications=summaries,
        unresolved_case_count=unresolved,
        questions_to_discuss=[q.question_text for q in questions],
        note=NOTE,
        lab_findings=_lab_findings(session, patient_id),
    )


def build_info_card(session: Session, *, user_id: str, household_member_id: str) -> dict:
    full = build_export(session, user_id=user_id, household_member_id=household_member_id)
    return {
        "generated_at": full.generated_at.isoformat(),
        "patient": full.patient_name,
        "current_medications": [
            {"name": m.name, "dose": m.current_dose} for m in full.medications
        ],
        "note": (
            "Medication information for sharing with a healthcare professional. "
            "Not an emergency-decision or triage tool."
        ),
    }
