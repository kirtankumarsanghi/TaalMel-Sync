"""Render the doctor export as a PDF.

WeasyPrint was the original choice but it needs GTK system libraries that are not
present on every machine. fpdf2 is pure Python and produces a usable, printable
document, so the export works everywhere with no system dependency.

The document is deliberately plain: a doctor reading it in a 10-minute appointment
needs medicine, dose, what happened, and what is unresolved. Nothing is interpreted.
"""

import io
from datetime import datetime

from fpdf import FPDF

from app.services.doctor_export import DoctorExport

MARGIN = 14
LINE = 4.6


class _Doc(FPDF):
    def header(self) -> None:  # noqa: D102 - fpdf hook
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(120, 120, 120)
        self.cell(0, 6, "Taalmel Sync  -  medication record", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(220, 220, 220)
        self.line(MARGIN, self.get_y() + 1, 210 - MARGIN, self.get_y() + 1)
        self.ln(4)

    def footer(self) -> None:  # noqa: D102 - fpdf hook
        self.set_y(-14)
        self.set_font("Helvetica", "I", 7.5)
        self.set_text_color(140, 140, 140)
        self.cell(0, 5, f"Page {self.page_no()}  -  generated by Taalmel Sync", align="C")


def _safe(text: str | None) -> str:
    """fpdf's core fonts are Latin-1; replace anything outside it rather than crash."""
    if not text:
        return ""
    return (
        text.replace("\u2014", "-")
        .replace("\u2013", "-")
        .replace("\u2019", "'")
        .replace("\u2018", "'")
        .replace("\u2192", "->")
        .encode("latin-1", "replace")
        .decode("latin-1")
    )


def render_pdf(export: DoctorExport) -> bytes:
    pdf = _Doc(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(MARGIN, 12, MARGIN)
    pdf.add_page()

    # Patient
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(12, 17, 16)
    pdf.cell(0, 9, _safe(export.patient_name), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 8.5)
    pdf.set_text_color(110, 110, 110)
    pdf.cell(
        0,
        5,
        _safe(f"Generated {export.generated_at.strftime('%d %b %Y, %H:%M UTC')}"
              f"   |   {export.unresolved_case_count} unresolved"),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(3)

    if not export.medications:
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(60, 60, 60)
        pdf.multi_cell(0, LINE, "No medicines recorded yet.", new_x="LMARGIN", new_y="NEXT")

    for med in export.medications:
        # Medicine heading
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(12, 17, 16)
        heading = med.name
        if med.current_dose:
            heading += f"   {med.current_dose}"
        pdf.cell(0, 6, _safe(heading), new_x="LMARGIN", new_y="NEXT")

        if med.prescribed_by:
            detail = f"Prescribed by {med.prescribed_by}"
            if med.prescribed_on:
                detail += f" on {med.prescribed_on.strftime('%d %b %Y')}"
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(120, 120, 120)
            pdf.cell(0, 4.5, _safe(detail), new_x="LMARGIN", new_y="NEXT")

        # Status line
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(70, 70, 70)
        dims = med.dimensions
        status_line = (
            f"Prescribed: {dims['prescribed']['status'].lower()}"
            f"   Patient reports: {dims['reported_taking']['status'].lower()}"
            f"   Stock: {dims['available']['status'].lower()}"
            f"   Confirmed: {dims['confirmed_status']['status'].lower()}"
        )
        pdf.multi_cell(0, LINE, _safe(status_line), new_x="LMARGIN", new_y="NEXT")

        if med.open_cases:
            pdf.set_font("Helvetica", "B", 8.5)
            pdf.set_text_color(150, 90, 10)
            pdf.cell(
                0, 4.5, _safe(f"{med.open_cases} unresolved issue(s) on this medicine"),
                new_x="LMARGIN", new_y="NEXT",
            )

        # Timeline, newest last so it reads as a history
        if med.timeline:
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(95, 95, 95)
            for entry in med.timeline[-8:]:
                when = entry.date.strftime("%d %b %Y")
                pdf.multi_cell(
                    0,
                    LINE,
                    _safe(f"  {when}  {entry.detail}  ({entry.source})"),
                    new_x="LMARGIN",
                    new_y="NEXT",
                )

        pdf.set_font("Helvetica", "I", 7.5)
        pdf.set_text_color(135, 135, 135)
        pdf.multi_cell(0, LINE, _safe(med.evidence_basis), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2.5)

    # Labs
    if export.lab_findings:
        pdf.set_font("Helvetica", "B", 10.5)
        pdf.set_text_color(12, 17, 16)
        pdf.cell(0, 7, "Lab results (shown as printed, not interpreted)", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(70, 70, 70)
        for finding in export.lab_findings:
            line = f"{finding['test_name']}: {finding['value']}"
            if finding.get("unit"):
                line += f" {finding['unit']}"
            if finding.get("captured_on"):
                line += f"   ({finding['captured_on']})"
            pdf.cell(0, LINE, _safe(line), new_x="LMARGIN", new_y="NEXT")

            window = (finding.get("adherence_before") or [{}])[0]
            if window.get("reported_adhered_percent") is not None:
                pdf.set_font("Helvetica", "I", 7.5)
                pdf.set_text_color(135, 135, 135)
                pdf.multi_cell(
                    0,
                    LINE,
                    _safe(
                        f"   {window.get('medication_name')} was reported taken on "
                        f"{window['reported_adhered_percent']}% of recorded days before this test."
                    ),
                    new_x="LMARGIN",
                    new_y="NEXT",
                )
                pdf.set_font("Helvetica", "", 8.5)
                pdf.set_text_color(70, 70, 70)
        pdf.ln(2)

    # Questions
    if export.questions_to_discuss:
        pdf.set_font("Helvetica", "B", 10.5)
        pdf.set_text_color(12, 17, 16)
        pdf.cell(0, 7, "Questions raised by the family", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(70, 70, 70)
        for question in export.questions_to_discuss:
            pdf.multi_cell(0, LINE, _safe(f"  -  {question}"), new_x="LMARGIN", new_y="NEXT")

    # Disclaimer
    pdf.ln(3)
    pdf.set_font("Helvetica", "I", 7.5)
    pdf.set_text_color(140, 140, 140)
    pdf.multi_cell(0, LINE, _safe(export.note), new_x="LMARGIN", new_y="NEXT")

    buffer = io.BytesIO()
    pdf.output(buffer)
    return buffer.getvalue()


def render_info_card_pdf(payload: dict) -> bytes:
    """A short card for handing to any healthcare professional. Not a triage tool."""
    pdf = _Doc(format="A5")
    pdf.set_auto_page_break(auto=True, margin=14)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(12, 17, 16)
    pdf.cell(0, 8, _safe(payload.get("patient", "Patient")), new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(120, 120, 120)
    pdf.cell(
        0, 5, _safe(f"Current medicines  -  {payload.get('generated_at', '')[:10]}"),
        new_x="LMARGIN", new_y="NEXT",
    )
    pdf.ln(2)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(40, 40, 40)
    for med in payload.get("current_medications", []):
        line = med.get("name", "")
        if med.get("dose"):
            line += f"   {med['dose']}"
        pdf.cell(0, 6, _safe(line), new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 7.5)
    pdf.set_text_color(140, 140, 140)
    pdf.multi_cell(0, 4.5, _safe(payload.get("note", "")), new_x="LMARGIN", new_y="NEXT")

    buffer = io.BytesIO()
    pdf.output(buffer)
    return buffer.getvalue()
