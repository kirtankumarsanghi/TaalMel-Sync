import { prisma } from '../db/client';
import { computeMedicationState } from '../engines/medicationStateEngine';
import { listCasesForMedication } from '../engines/caseLifecycle';

export async function buildDoctorExport(householdMemberId: string) {
  const member = await prisma.householdMember.findUnique({ where: { id: householdMemberId } });
  if (!member) throw new Error(`Household member not found: ${householdMemberId}`);

  const medications = await prisma.medication.findMany({
    where: { householdMemberId }
  });

  const medicationSummaries = await Promise.all(medications.map(async (med) => {
    const state = await computeMedicationState(med.id);
    const cases = await listCasesForMedication(med.id);
    return {
      medicationId: med.id,
      name: med.nameGeneric || med.nameRaw,
      currentDose: state.currentDose,
      dimensions: state.dimensions,
      openCases: cases.filter((c) => ['OPEN', 'AWAITING_INFO'].includes(c.status)),
      resolvedCases: cases.filter((c) => c.status === 'RESOLVED'),
      stillUncertainCases: cases.filter((c) => c.status === 'STILL_UNCERTAIN'),
    };
  }));

  const pendingQuestions = await prisma.doctorQuestion.findMany({
    where: {
      householdMemberId,
      status: 'PENDING'
    },
    orderBy: { createdAt: 'asc' }
  });

  return {
    generatedAt: new Date().toISOString(),
    patient: { id: member.id, name: member.displayName },
    medications: medicationSummaries,
    unresolvedCaseCount: medicationSummaries.reduce((sum, m) => sum + m.openCases.length, 0),
    questionsToDiscuss: pendingQuestions.map((q) => q.questionText),
    note: 'Generated by Taalmel Sync. This is a structured summary for clinical review, not a diagnosis or treatment recommendation.',
  };
}

export async function buildMinimalInfoCard(householdMemberId: string) {
  const full = await buildDoctorExport(householdMemberId);
  return {
    generatedAt: full.generatedAt,
    patient: full.patient,
    currentMedications: full.medications.map((m) => ({ name: m.name, dose: m.currentDose })),
    lastUpdated: full.generatedAt,
    note: 'Medication information for sharing with a healthcare professional. Not an emergency-decision or triage tool.',
  };
}

